# ============================================================
# 05. datetime 模块
# ============================================================
# 大纲：
#   - date：日期对象
#   - time：时间对象
#   - datetime：日期时间对象（最常用）
#   - timedelta：时间差
#   - 获取当前时间：datetime.now(), date.today()
#   - 字符串 ↔ 时间：strptime() / strftime()
#   - 时间戳 ↔ 时间：fromtimestamp() / .timestamp()
#   - 时区处理：timezone, utc, astimezone()
#   - 日期计算：加减 timedelta
#   - 日期比较：== < >
#   - ISO 格式：.isoformat(), fromisoformat()
#   - calendar 模块：日历相关操作
#   - 实用技巧：计算两个日期相差多少天、判断星期几
#   - dateutil 库简介（更强大的日期解析，非标准库）
