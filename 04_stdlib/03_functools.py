# 03. functools 模块
# ============================================================
# 大纲：
#   - reduce()：累积计算（map-reduce 中的 reduce）
#   - partial()：偏函数（固定部分参数）
#   - lru_cache() / cache()：函数结果缓存（最常用的装饰器之一）
#   - cached_property()：缓存属性（计算一次，之后直接取）
#   - wraps()：保留被装饰函数的元信息
#   - singledispatch()：单分派泛型函数（按第一个参数类型分发）
#   - total_ordering()：只写两个比较方法，其他的自动生成
#   - cmp_to_key()：把旧式比较函数转为 key 函数
#   - partialmethod()：方法级别的偏函数
