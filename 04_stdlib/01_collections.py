# 01. collections 模块
# ============================================================
# 大纲：
#   - namedtuple：有字段名的元组
#   - deque：双端队列（高效的头尾插入删除）
#   - Counter：计数器（统计频次）
#   - defaultdict：有默认值的字典
#   - OrderedDict：有序字典（Python 3.7+ 普通 dict 也是有序的）
#   - ChainMap：链式字典（合并多个字典但保持独立）
#   - UserDict / UserList / UserString：自定义容器基类
#   - 各类型的使用场景和性能对比
