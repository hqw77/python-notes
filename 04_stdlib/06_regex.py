# ============================================================
# 06. re 模块（正则表达式）
# ============================================================
# 大纲：
#   - 什么是正则表达式
#   - 基本模式：., *, +, ?, {m,n}, ^, $, [...], [^...]
#   - 转义字符：\d, \w, \s, \D, \W, \S
#   - 分组：() 和 非捕获分组 (?:)
#   - 命名分组：(?P<name>...)
#   - 或：|
#   - 贪婪 vs 非贪婪：.* vs .*?
#   - 前瞻/后顾：(?=...), (?!...), (?<=...), (?<!...)
#   - re.search()：搜索第一个匹配
#   - re.match()：从开头匹配
#   - re.findall()：找到所有匹配
#   - re.finditer()：迭代匹配
#   - re.sub()：替换
#   - re.split()：按正则分割
#   - re.compile()：预编译正则（提高重复使用性能）
#   - Match 对象：.group(), .groups(), .groupdict()
#   - 原始字符串 r"..." 的重要性
#   - 常用正则示例：邮箱、手机号、URL、IP 地址
